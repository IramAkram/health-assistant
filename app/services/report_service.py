"""PDF health-summary generation with ReportLab (pure: takes plain data, returns bytes)."""
from datetime import datetime
from io import BytesIO
from typing import Any

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

LABELS = {
    "systolic": "Systolic BP (mmHg)", "diastolic": "Diastolic BP (mmHg)", "glucose": "Glucose (mg/dL)",
    "weight_kg": "Weight (kg)", "sleep_hours": "Sleep (hours)", "exercise_minutes": "Exercise (min)",
    "stress_level": "Stress (1-10)",
}
TEAL = colors.HexColor("#0E7C7B")


def _table(data, col_widths=None):
    t = Table(data, colWidths=col_widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), TEAL),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTSIZE", (0, 0), (-1, -1), 8.5),
        ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#B8C7C7")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F1F6F6")]),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    return t


def build_pdf(user: dict[str, Any], days: int, summary: dict[str, Any], records: list[dict[str, Any]],
              alerts: list[dict[str, Any]], risk: dict[str, Any]) -> bytes:
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=1.8 * cm, rightMargin=1.8 * cm,
                            topMargin=1.6 * cm, bottomMargin=1.6 * cm, title="Health Summary Report")
    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Title"], textColor=TEAL, fontSize=20, alignment=0)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], textColor=colors.HexColor("#14282E"), spaceBefore=12)
    body = ss["BodyText"]
    small = ParagraphStyle("small", parent=body, fontSize=8, textColor=colors.HexColor("#555555"))

    s: list = [Paragraph("Health Summary Report", h1)]
    s.append(Paragraph(
        f"<b>{user['full_name']}</b> &nbsp;|&nbsp; Period: last {days} days &nbsp;|&nbsp; "
        f"Generated: {datetime.now().strftime('%d %b %Y, %H:%M')}", body))
    prof = []
    if user.get("age") is not None: prof.append(f"Age: {user['age']}")
    if user.get("height_cm"): prof.append(f"Height: {user['height_cm']:g} cm")
    if user.get("bmi"): prof.append(f"BMI: {user['bmi']}")
    if user.get("health_goal"): prof.append(f"Goal: {user['health_goal']}")
    if prof:
        s.append(Paragraph(" &nbsp;|&nbsp; ".join(prof), body))

    s.append(Paragraph("1. Measured values (summary)", h2))
    rows = [["Measurement", "Readings", "Average", "Min", "Max", "Latest", "Trend"]]
    for key, m in summary.get("metrics", {}).items():
        rows.append([LABELS.get(key, key), m["count"], m["mean"], m["min"], m["max"], m["latest"], m["trend"]])
    if len(rows) == 1:
        s.append(Paragraph("No measurements were recorded in this period.", body))
    else:
        s.append(_table(rows))

    s.append(Paragraph("2. Model estimate (informational)", h2))
    if risk.get("available"):
        s.append(Paragraph(
            f"Estimated diabetes-risk level: <b>{risk['band']}</b> "
            f"(probability {risk['probability'] * 100:.0f}%). {risk['disclaimer']}", body))
    else:
        s.append(Paragraph(risk.get("reason", "Not available."), body))

    s.append(Paragraph("3. Alerts raised by rule-based checks", h2))
    if alerts:
        s.append(_table([["Date", "Level", "Message"]] + [
            [a["created_at"].strftime("%d %b %H:%M"), a["severity"], Paragraph(a["message"], small)] for a in alerts[:25]
        ], [2.6 * cm, 2 * cm, 12.8 * cm]))
    else:
        s.append(Paragraph("No alerts in this period.", body))

    s.append(Paragraph("4. Recent records", h2))
    if records:
        rows = [["Date", "BP", "Glucose", "Weight", "Sleep", "Exercise", "Stress"]]
        for r in records[-30:]:
            bp = f"{r['systolic']}/{r['diastolic']}" if r.get("systolic") else "-"
            f = lambda v: "-" if v is None else f"{v:g}"
            rows.append([r["recorded_at"].strftime("%d %b %H:%M"), bp, f(r["glucose"]), f(r["weight_kg"]),
                         f(r["sleep_hours"]), f(r["exercise_minutes"]), f(r["stress_level"])])
        s.append(_table(rows))
    else:
        s.append(Paragraph("No records.", body))

    s.append(Spacer(1, 14))
    s.append(Paragraph(
        "<b>Important:</b> This report is generated by a personal wellness-tracking tool. It does not diagnose "
        "disease, prescribe treatment, or replace professional medical advice. Share it with your doctor if you "
        "have health concerns.", small))
    doc.build(s)
    return buf.getvalue()
